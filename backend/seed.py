def seed_all(db: Session = None):
    should_close = False
    if db is None:
        Base.metadata.create_all(bind=engine)
        db = SessionLocal()
        should_close = True

    print("--- PharmaPulse Synthetic Seeder Started ---")

    # Clear existing data for fresh seed if needed
    db.query(Report).delete()
    db.query(Notification).delete()
    db.query(Signal).delete()
    db.query(Inventory).delete()
    db.query(SalesData).delete()
    db.query(MedicineCategory).delete()
    db.query(Pharmacy).delete()
    db.query(User).delete()
    db.commit()

    # 1. Seed Users
    print("Seeding demo user accounts...")
    user_objects = []
    for u in DEMO_USERS:
        user = User(
            email=u["email"],
            hashed_password=get_password_hash(u["password"]),
            full_name=u["full_name"],
            role=u["role"]
        )
        db.add(user)
        user_objects.append(user)
    db.commit()

    # 2. Seed Medicine Categories
    print("Seeding 10 medicine categories...")
    category_objects = []
    for c in CATEGORIES:
        cat = MedicineCategory(
            code=c["code"],
            name=c["name"],
            description=c["desc"],
            priority_level=c["priority"]
        )
        db.add(cat)
        category_objects.append(cat)
    db.commit()

    # 3. Seed 55 Pharmacies across 10 zones
    print("Seeding 55 synthetic pharmacies in Chennai zones...")
    pharmacy_objects = []
    pharma_names_prefixes = ["MedPlus", "Apollo Pharmacy", "Wellness Forever", "LifeCare Chemist", "Cauvery Medicos", "City Health Drugstore"]
    
    idx = 1
    for zone in ZONES:
        # 5 to 6 pharmacies per zone
        count_in_zone = 6 if zone["name"] in ["Zone 4", "Zone 7", "Zone 2"] else 5
        for j in range(count_in_zone):
            code = f"PH-{idx:03d}"
            # Slightly jitter coordinates within 0.015 degrees (~1.5 km)
            lat_jitter = zone["lat"] + random.uniform(-0.015, 0.015)
            lng_jitter = zone["lng"] + random.uniform(-0.015, 0.015)
            name = f"{random.choice(pharma_names_prefixes)} #{idx} ({zone['name']})"

            ph = Pharmacy(
                code=code,
                name=name,
                zone=zone["name"],
                address=f"Plot {10 + idx}, {zone['area']}, Chennai - 6000{idx%90 + 10}",
                latitude=round(lat_jitter, 6),
                longitude=round(lng_jitter, 6),
                contact_person=f"Pharmacist {code}",
                phone=f"+91-9840{idx:02d}4411",
                is_active=True
            )
            db.add(ph)
            pharmacy_objects.append(ph)
            idx += 1
    db.commit()

    # 4. Seed Inventory Records
    print("Seeding category inventories and supply pressure signals...")
    for ph in pharmacy_objects:
        for cat in category_objects:
            # Baseline inventory levels
            is_zone4_resp = (ph.zone == "Zone 4" and cat.name in ["Respiratory", "Cough/Cold"])
            is_zone7_fev = (ph.zone == "Zone 7" and cat.name in ["Fever", "Pain Relief"])

            if is_zone4_resp:
                current_stock = random.randint(25, 45)
                stock_pct = random.randint(28, 48)
                supply_risk = "HIGH"
                demand_trend = round(random.uniform(75.0, 92.0), 1)
            elif is_zone7_fev:
                current_stock = random.randint(40, 60)
                stock_pct = random.randint(45, 62)
                supply_risk = "MEDIUM"
                demand_trend = round(random.uniform(50.0, 70.0), 1)
            else:
                current_stock = random.randint(90, 160)
                stock_pct = random.randint(80, 100)
                supply_risk = "LOW"
                demand_trend = round(random.uniform(-5.0, 15.0), 1)

